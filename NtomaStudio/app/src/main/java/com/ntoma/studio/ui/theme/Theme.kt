    extraLarge = RoundedCornerShape(24.dp),
)

@Composable
fun NtomaTheme(content: @Composable () -> Unit) {
    val prefs = AppContainer.get(LocalContext.current).settings.preferences
        .collectAsStateWithLifecycle(initialValue = com.ntoma.studio.domain.model.UserPreferences())
    val systemDark = isSystemInDarkTheme()
    val dark = when (prefs.value.themeMode) {
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
        ThemeMode.SYSTEM -> systemDark
    }
    MaterialTheme(
        colorScheme = if (dark) DarkScheme else LightScheme,
        typography = NtomaTypography,
        shapes = NtomaShapes,
        content = content,
    )
}

/** Build version guard kept for clarity; we use fixed brand schemes on all versions. */
@Suppress("UNUSED_PARAMETER")
private fun dynamicColorAvailable(): Boolean = Build.VERSION.SDK_INT >= 31
